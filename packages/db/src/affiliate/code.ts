import { CLICK_COOKIE_MAX_IDS } from "./settings.ts";

// Pure helpers for the affiliate selectors (T-52): the typed code, the click id and the continuity cookie. No I/O. A selector is never authority:
// everything parsed here is only handed to the database, which decides whether it names an eligible affiliate for the store being checked out.

/** Allowed raw characters of a typed code: letters, digits and the separators people type. Anything else (including every non-ASCII letter) is not a code. */
const TYPED_CODE_RE = /^[A-Za-z0-9 _-]{1,64}$/;
/** What the database stores and compares: upper-case letters and digits, 4 to 24 (`affiliate_code_form_chk`). */
export const NORMALIZED_CODE_RE = /^[A-Z0-9]{4,24}$/;
/** An opaque click id: `c` plus 32 lower-case hex characters, generated by the database (`affiliate_click_id_chk`). */
export const CLICK_ID_RE = /^c[0-9a-f]{32}$/;
/** The public link token: random, URL-safe (`affiliate_link_token_chk`). */
export const LINK_TOKEN_RE = /^[A-Za-z0-9_-]{16,64}$/;

/**
 * The one normalisation of an affiliate code: trimmed, separators (space, `-`, `_`) removed, upper-cased, then it must be 4 to 24 letters or digits.
 * ASCII only, checked BEFORE upper-casing, so a character such as the Kelvin sign or a dotless i can never fold into a code that belongs to someone else.
 * `null` for anything that is not a usable code (the caller treats that as "no code", never as an error).
 */
export function normalizeAffiliateCode(raw: unknown): string | null {
  if (typeof raw !== "string" || !TYPED_CODE_RE.test(raw.trim())) return null;
  const code = raw.trim().replace(/[ _-]/g, "").toUpperCase();
  return NORMALIZED_CODE_RE.test(code) ? code : null;
}

/** The click ids carried by a continuity cookie: well-formed ids only, newest first, no duplicates, at most `CLICK_COOKIE_MAX_IDS`. Anything else in the value is dropped. */
export function parseReferralCookie(value: string | null | undefined): string[] {
  if (!value || value.length > 512) return [];
  const out: string[] = [];
  for (const part of value.split(".")) if (CLICK_ID_RE.test(part) && !out.includes(part)) out.push(part);
  return out.slice(0, CLICK_COOKIE_MAX_IDS);
}

/** The cookie value after a new capture: the new id first, then the previous ones, capped. */
export function addReferralClick(existing: string | null | undefined, clickId: string): string {
  return [clickId, ...parseReferralCookie(existing).filter((id) => id !== clickId)].slice(0, CLICK_COOKIE_MAX_IDS).join(".");
}

export type ClickRequestFacts = { method: string; headers: { get(name: string): string | null } };
export type ClickDecision = "capture" | "non_navigation";

/**
 * SEC-20: a click is captured only for a top-level navigation: method GET, `Sec-Fetch-Mode: navigate`, `Sec-Fetch-Dest: document`, and not a prefetch or
 * prerender (`Sec-Purpose`, `Purpose`). Everything else (HEAD, an `<img>`, an iframe, a script, a fetch, a request without Fetch Metadata) is redirected
 * without a click, so embedding a link in a page cannot stuff the visitor's cookie.
 */
export function classifyClickRequest(req: ClickRequestFacts): ClickDecision {
  if (req.method.toUpperCase() !== "GET") return "non_navigation";
  const h = req.headers;
  if (h.get("sec-fetch-mode")?.toLowerCase() !== "navigate" || h.get("sec-fetch-dest")?.toLowerCase() !== "document") return "non_navigation";
  const speculative = `${h.get("sec-purpose") ?? ""} ${h.get("purpose") ?? ""}`.toLowerCase();
  return /prefetch|prerender/.test(speculative) ? "non_navigation" : "capture";
}
